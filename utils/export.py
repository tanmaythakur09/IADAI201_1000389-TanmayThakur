def sanitize_for_pdf(text: str) -> str:
    """
    Replaces Unicode punctuation (em/en dashes, smart quotes, symbols)
    with plain ASCII equivalents to ensure compatibility with standard FPDF core fonts.
    """
    if not text:
        return ""
    replacements = {
        "—": "-",    # em-dash (\u2014)
        "–": "-",    # en-dash (\u2013)
        "“": '"',    # left double curly quote
        "”": '"',    # right double curly quote
        "‘": "'",    # left single curly quote
        "’": "'",    # right single curly quote
        "…": "...",  # horizontal ellipsis
        "→": "->",   # right arrow
        "←": "<-",   # left arrow
        "•": "*",    # bullet
        "≥": ">=",
        "≤": "<=",
        "×": "x",
        "±": "+/-",
        "°": " deg",
    }
    for orig, repl in replacements.items():
        text = text.replace(orig, repl)
    # Ensure all remaining characters fall safely within latin-1
    return text.encode("latin-1", "replace").decode("latin-1")


def generate_csv_report(results: List[SlotResult], positions: List[Dict[str, Any]]) -> str:
    """Generates a CSV string containing detailed slot-level detection results."""
    pos_map = {p["id"]: p for p in positions}
    records = []
    for r in sorted(results, key=lambda x: x.slot_id):
        p = pos_map.get(r.slot_id, {})
        records.append({
            "Slot_ID": r.slot_id,
            "Status": "Occupied" if r.occupied else "Empty",
            "Confidence_Pct": round(r.confidence * 100, 1),
            "Box_X": p.get("x", ""),
            "Box_Y": p.get("y", ""),
            "Box_Width": p.get("w", ""),
            "Box_Height": p.get("h", ""),
        })
    df = pd.DataFrame(records)
    return df.to_csv(index=False)


class ParkingPDFReport(FPDF):
    def header(self):
        self.set_fill_color(15, 23, 42)  # Dark slate header bar
        self.rect(0, 0, 210, 22, "F")
        self.set_xy(12, 6)
        self.set_font("Helvetica", "B", 15)
        self.set_text_color(255, 255, 255)
        self.cell(0, 8, sanitize_for_pdf("ParkVision AI | Intelligent Parking Analytics"), new_x=XPos.RIGHT, new_y=YPos.TOP)
        self.set_font("Helvetica", "", 9)
        self.set_xy(145, 8)
        self.set_text_color(148, 163, 184)
        self.cell(55, 6, "CONFIDENTIAL REPORT", align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(12)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(156, 163, 175)
        footer_text = f"Generated by ParkVision AI - UrbanFlow AI Pvt. Ltd. - Page {self.page_no()}"
        self.cell(0, 10, sanitize_for_pdf(footer_text), align="C")


def generate_pdf_report(
    summary: LotSummary,
    annotated_image: Image.Image,
    image_name: str = "parking_lot.jpg",
) -> bytes:
    """
    Generates a concise, portfolio-grade one-page executive summary PDF report.
    Returns bytes of the compiled PDF.
    """
    pdf = ParkingPDFReport(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=False)
    pdf.add_page()

    # Meta Info Subtitle
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(30, 41, 59)
    clean_title = sanitize_for_pdf(f"Lot Audit Summary: {image_name}")
    pdf.cell(0, 6, clean_title, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(100, 116, 139)
    timestamp_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    sub_text = sanitize_for_pdf(f"Analysis Executed: {timestamp_str} | Vision Engine: MobileNetV2 (PKLot)")
    pdf.cell(0, 5, sub_text, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(3)

    # KPI Table Banner
    pdf.set_fill_color(241, 245, 249)
    pdf.rect(10, 36, 190, 22, "F")
    pdf.set_xy(12, 38)

    # 4 KPI columns
    pdf.set_font("Helvetica", "B", 8)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(47, 5, "TOTAL CAPACITY", align="C")
    pdf.cell(47, 5, "OCCUPIED SPACES", align="C")
    pdf.cell(47, 5, "AVAILABLE SPACES", align="C")
    pdf.cell(47, 5, "OCCUPANCY RATE", align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_xy(12, 44)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(47, 8, str(summary.total_slots), align="C")
    pdf.set_text_color(220, 38, 38)
    pdf.cell(47, 8, str(summary.occupied_slots), align="C")
    pdf.set_text_color(16, 185, 129)
    pdf.cell(47, 8, str(summary.available_slots), align="C")
    pdf.set_text_color(37, 99, 235)
    pdf.cell(47, 8, f"{summary.occupancy_pct}%", align="C", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.ln(5)

    # Congestion & Recommendation Alert Box
    if summary.congestion == "Low":
        r, g, b = 236, 253, 245
        br, bg, bb = 16, 185, 129
        text_color = (6, 95, 70)
    elif summary.congestion == "Moderate":
        r, g, b = 254, 243, 199
        br, bg, bb = 217, 119, 6
        text_color = (146, 64, 14)
    else:
        r, g, b = 254, 242, 242
        br, bg, bb = 220, 38, 38
        text_color = (153, 27, 27)

    pdf.set_fill_color(r, g, b)
    pdf.set_draw_color(br, bg, bb)
    pdf.set_line_width(0.5)
    pdf.rect(10, 62, 190, 18, "DF")

    pdf.set_xy(14, 64)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*text_color)
    cong_label = sanitize_for_pdf(f"Congestion Status: {summary.congestion.upper()}")
    pdf.cell(0, 5, cong_label, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_xy(14, 70)
    pdf.set_font("Helvetica", "", 9)
    clean_rec = sanitize_for_pdf(summary.recommendation)
    pdf.multi_cell(182, 4.5, clean_rec)

    pdf.ln(5)

    # Image Section
    pdf.set_xy(10, 84)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(15, 23, 42)
    img_heading = sanitize_for_pdf("Computer Vision Slot Annotation (Green = Available, Red = Occupied):")
    pdf.cell(0, 6, img_heading, new_x=XPos.LMARGIN, new_y=YPos.NEXT)


    # Save PIL image to temporary file to embed in PDF
    with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as tmp:
        annotated_image.save(tmp.name, format="PNG")
        tmp_path = tmp.name

    try:
        pdf.image(tmp_path, x=10, y=92, w=190)
    finally:
        Path(tmp_path).unlink(missing_ok=True)

    # Technical Footnote
    pdf.set_xy(10, 252)
    pdf.set_font("Helvetica", "", 7.5)
    pdf.set_text_color(148, 163, 184)
    footnote = sanitize_for_pdf(
        "System notes: Image processed via ParkVision AI edge pipeline. MobileNetV2 classification on 224x224 crops. "
        "Threshold metrics: Low (<40%), Moderate (40-75%), High (>75%). For camera reconfiguration or re-calibration, "
        "refer to the UrbanFlow AI systems administrator."
    )
    pdf.multi_cell(190, 3.5, footnote)

    return bytes(pdf.output())
